"""EvilGenius's site draws with the firmware's own art: art-eg/*.txt (the two pixel fonts, the sprites, the palette)
-> site/js/pxart.js, the data site/js/px.js draws from (<px-text>, <px-sprite>). Run after editing the art, with
tools/eg/gen_art.py:  tools/eg/gen_site_art.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "art-eg"))
import eglib  # noqa: E402


def font(f):
    """{cw, ch, g: {char: [row bits as a string of 0 / 1]}}"""
    return {"cw": f["cw"], "ch": f["ch"],
            "g": {ch: ["".join(str(v) for v in row) for row in rows] for ch, rows in sorted(f["g"].items())}}


def main():
    hexd = "0123456789abcdef"
    sprites = {name: ["".join("." if v == eglib.T else hexd[v] for v in row) for row in rows]
               for name, rows in eglib.SPR.items()}
    data = {"pal": ["#%02x%02x%02x" % c for c in eglib.PAL], "names": eglib.NAMES,
            "big": font(eglib.BIG), "small": font(eglib.SMALL), "spr": sprites}
    out = ROOT / "site" / "js" / "pxart.js"
    out.write_text("/* generated by tools/eg/gen_site_art.py from art-eg/: do not edit (edit the art, run the tool).\n"
                   " * EvilGenius's own pixel art (MPL-2.0): the C64's sixteen colours (Colodore), the two fonts, the sprites */\n"
                   "export const PXART = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n",
                   encoding="utf-8")
    print(f"gen_site_art: {len(sprites)} sprites, 2 fonts -> {out} ({out.stat().st_size} B)")


if __name__ == "__main__":
    main()
