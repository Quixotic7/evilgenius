#!/usr/bin/env python3
"""EvilGenius: art-eg/*.txt (the two pixel fonts, the sprites) -> core/ui/px_art.h, the pixel kit's data
(core/ui/px.c). Run after editing the art: tools/eg/gen_art.py

The fonts: a glyph's rows as bytes, bit 7 its leftmost pixel; ASCII 32..126 by code, the others (· × → ← … ° ±) in
PX_XCHAR's order after 126. The sprites: their pixels as C64 colour numbers, 0xFF transparent."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "art-eg"))
import eglib  # noqa: E402

EXTRA = ["·", "×", "→", "←", "…", "°", "±"]
# The sprites kept as rectangles, not pixels: the Evil Genius's machine and its laugh. As runs of a row the machine is
# 1,091 rectangles a frame and the idle screen 2,300 to 2,770, at the edge of what the unit's frame holds (2,816: over
# it the screen is drawn again for every band, and the idle screen stuttered); as rectangles laid over one another it is
# 645, and smaller in the flash than its 8,800 pixels. (The floor's tile too: thirteen of them a frame.)
RECTS = {"GENIUS_BIG", "GENIUS_HA", "FLOOR"}


def rects(rows):
    """The picture as rectangles of one colour, painted in order, a later one over an earlier: the colours from the
    most pixels to the fewest, and a colour's rectangle may run across pixels of the colours still to come (they are
    painted over it), never an open pixel or a colour already down. From each pixel of the colour not yet covered:
    as far right as that allows (back to its last pixel of the colour), then down the same way."""
    from collections import Counter
    h, w = len(rows), len(rows[0])
    order = [c for c, _ in Counter(v for r in rows for v in r if v != eglib.T).most_common()]
    rank = {c: i for i, c in enumerate(order)}
    out = []
    for k, c in enumerate(order):
        ok = [[rows[y][x] != eglib.T and rank[rows[y][x]] >= k for x in range(w)] for y in range(h)]
        need = [[rows[y][x] == c for x in range(w)] for y in range(h)]
        for y in range(h):
            for x in range(w):
                if not need[y][x]:
                    continue
                x1 = x
                while x1 + 1 < w and ok[y][x1 + 1]:
                    x1 += 1
                while x1 > x and not need[y][x1]:
                    x1 -= 1
                y1 = y
                while (y1 + 1 < h and all(ok[y1 + 1][i] for i in range(x, x1 + 1))
                       and any(need[y1 + 1][i] for i in range(x, x1 + 1))):
                    y1 += 1
                while x1 > x and not any(need[j][x1] for j in range(y, y1 + 1)):
                    x1 -= 1
                for j in range(y, y1 + 1):
                    for i in range(x, x1 + 1):
                        need[j][i] = False
                out.append((x, y, x1 - x + 1, y1 - y + 1, c))
    got = [[eglib.T] * w for _ in range(h)]              # (checked: the rectangles make the picture)
    for x, y, n, m, c in out:
        for j in range(y, y + m):
            for i in range(x, x + n):
                got[j][i] = c
    assert got == [list(r) for r in rows]
    return out


def font_c(name, font, rows):
    g = font["g"]
    out = [f"static const uint8_t {name}_ROWS[{95 + len(EXTRA)}][{rows}] = {{"]
    widths = []
    for i in range(95 + len(EXTRA)):
        ch = chr(32 + i) if i < 95 else EXTRA[i - 95]
        bm = g.get(ch) or g.get(ch.upper())
        if ch == " " or bm is None:
            out.append("    {" + ",".join(["0"] * rows) + "},")
            widths.append(0)
            continue
        vals = []
        for r in range(rows):
            row = bm[r] if r < len(bm) else []
            b = 0
            for x, v in enumerate(row[:8]):
                if v:
                    b |= 0x80 >> x
            vals.append(f"0x{b:02X}")
        widths.append(max((x + 1 for r in bm for x, v in enumerate(r[:8]) if v), default=0))
        out.append("    {" + ",".join(vals) + f"}},   /* {ch!r} */")
    out.append("};")
    return "\n".join(out)


def main():
    lines = ["/* generated by tools/eg/gen_art.py from the art-eg text files: do not edit (edit the art, run the tool) */",
             "#pragma once", "#include <stdint.h>", "",
             f"#define PX_NXCHAR {len(EXTRA)}",
             "static const uint32_t PX_XCHAR[PX_NXCHAR] = {" + ", ".join(f"0x{ord(c):04X}" for c in EXTRA) + "};",
             "/* the C64's 16 colours (Colodore) */",
             "static const uint32_t PX_PAL[16] = {" + ", ".join(f"0x{r:02x}{g:02x}{b:02x}u" for r, g, b in eglib.PAL)
             + "};", "",
             font_c("PX_FONT_S", eglib.SMALL, 5), "", font_c("PX_FONT_B", eglib.BIG, 7), ""]
    names = []
    for name, rows in eglib.SPR.items():
        w, h = len(rows[0]), len(rows)
        if name in RECTS:                               # a big picture: its rectangles (x, y, w, h, colour)
            rs = rects(rows)
            flat = [v for r in rs for v in r]
            lines.append(f"static const uint8_t PX_SPR_{name}_D[{len(flat)}] = {{" + ",".join(map(str, flat)) + "};")
            names.append((name, w, h, len(rs)))
            continue
        flat = [255 if v == eglib.T else v for r in rows for v in r]
        lines.append(f"static const uint8_t PX_SPR_{name}_D[{w * h}] = {{" + ",".join(map(str, flat)) + "};")
        names.append((name, w, h, 0))
    lines.append("/* d: w x h pixels (a C64 colour, 255 open); nr over 0: nr rectangles instead, five bytes each */")
    lines.append("typedef struct { uint8_t w, h; uint16_t nr; const uint8_t *d; } px_sprite_t;")
    lines.append('#include "px_ids.h"')
    (ROOT / "core" / "ui" / "px_ids.h").write_text(
        "/* generated by tools/eg/gen_art.py: the sprites' numbers (px_art.h has their pixels) */\n#pragma once\n"
        "enum { " + ", ".join(f"PXS_{n}" for n, _, _, _ in names) + ", PXS_N };\n")
    lines.append("static const px_sprite_t PX_SPR[PXS_N] = {")
    for n, w, h, nr in names:
        lines.append(f"    {{{w}, {h}, {nr}, PX_SPR_{n}_D}},")
    lines.append("};")
    out = ROOT / "core" / "ui" / "px_art.h"
    out.write_text("\n".join(lines) + "\n")
    print(f"gen_art: {len(names)} sprites, 2 fonts -> {out}")


if __name__ == "__main__":
    main()
