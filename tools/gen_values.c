/* EvilGenius's sound values (SID TONE: quad_voice.h, QD_QUAD_NP of them) as the web manager's sound editor shows them,
 * written from the core itself (qd_quad_value_name, qd_quad_value_range, qd_quad_value_text, qd_quad_lockable, the
 * modulation destinations' names and their order), so the page's names, ranges and texts are the unit's own:
 *
 *   build/gen_values > ../site/manager/egvalues.js      (make -C tools values; make -C tools values-check compares)
 *
 * Each value: its name, min, max, default, and its texts as a rule plus the exceptions: "int" (the number), "ofs" (+n
 * above 0), "c64" (stored centred on 64: v - 64, +n above), "fix2" / "fix2s" (hundredths), or "list" (every text, an
 * enumeration); the exceptions the values whose text differs from the rule (OFF, INF ..). Adapted from FIZZ's
 * tools/gen_values.c (MPL-2.0). */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "quad_voice.h"

static void rule_text(const char *rule, int v, char *out)
{
    const int a = v < 0 ? -v : v;
    if (!strcmp(rule, "ofs"))
        sprintf(out, v > 0 ? "+%d" : "%d", v);
    else if (!strcmp(rule, "c64"))
        sprintf(out, v > 64 ? "+%d" : "%d", v - 64);
    else if (!strcmp(rule, "fix2"))
        sprintf(out, "%d.%02d", a / 100, a % 100);
    else if (!strcmp(rule, "fix2s"))
        sprintf(out, "%c%d.%02d", v < 0 ? '-' : '+', a / 100, a % 100);
    else
        sprintf(out, "%d", v);
}

static void js_str(const char *s)
{
    putchar('"');
    for (; *s; s++) {
        if (*s == '"' || *s == '\\')
            putchar('\\');
        putchar(*s);
    }
    putchar('"');
}

int main(void)
{
    static const char *const RULES[5] = {"int", "ofs", "c64", "fix2", "fix2s"};
    int i, v, k;
    printf("// SPDX-License-Identifier: MPL-2.0\n");
    printf("// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of the MPL was not\n");
    printf("// distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.\n");
    printf("// GENERATED by tools/gen_values.c from EvilGenius's core (make -C tools values): do not edit. The %d SID TONE\n", QD_QUAD_NP);
    printf("// sound values as the unit names and shows them: [name, min, max, default, rule, exceptions | texts, lockable];\n");
    printf("// rule \"int\", \"ofs\" (+n), \"c64\" (v - 64, +n), \"fix2\" / \"fix2s\" (hundredths), \"list\" (the texts, min first).\n");
    printf("// DESTS: the modulation destinations' names (QD_D_*); DEST_ID: the value each one moves (-1: none of its own,\n");
    printf("// PITCH, PAN ..); DEST_ORDER: their order on the unit's DEST value.\n");
    printf("export const VALUES = [\n");
    for (i = 0; i < QD_QUAD_NP; i++) {
        int16_t mn, mx, df;
        char buf[16], want[16];
        const char *rule = 0;
        int best = -1, bestn = 1 << 30;
        if (!qd_quad_value_range(i, &mn, &mx, &df)) {
            fprintf(stderr, "gen_values: value %d has no range\n", i);
            return 1;
        }
        for (k = 0; k < 5; k++) {               /* the rule with the fewest exceptions */
            int n = 0;
            for (v = mn; v <= mx; v++) {
                qd_quad_value_text(i, v, buf);
                rule_text(RULES[k], v, want);
                n += strcmp(buf, want) != 0;
            }
            if (n < bestn)
                bestn = n, best = k;
        }
        rule = bestn > 8 && mx - mn < 1024 ? "list" : RULES[best];
        printf("  [");
        js_str(qd_quad_value_name(i));
        printf(", %d, %d, %d, \"%s\", ", mn, mx, df, rule);
        if (!strcmp(rule, "list")) {
            printf("[");
            for (v = mn; v <= mx; v++) {
                js_str(qd_quad_value_text(i, v, buf));
                if (v < mx)
                    putchar(',');
            }
            printf("]");
        } else {
            if (bestn > 64) {
                fprintf(stderr, "gen_values: value %d (%s): %d texts off its best rule %s\n", i, qd_quad_value_name(i), bestn,
                        rule);
                return 1;
            }
            printf("{");
            for (v = mn, k = 0; v <= mx; v++) {
                qd_quad_value_text(i, v, buf);
                rule_text(rule, v, want);
                if (strcmp(buf, want)) {
                    printf("%s\"%d\":", k++ ? "," : "", v);
                    js_str(buf);
                }
            }
            printf("}");
        }
        printf(", %d],  // %d\n", qd_quad_lockable(i) ? 1 : 0, i);
    }
    printf("];\n");
    printf("export const DESTS = [");
    for (k = 0; k < qd_quad_ndest(); k++) {
        if (k)
            putchar(',');
        js_str(qd_quad_dest_name(k));
    }
    printf("];\n");
    printf("export const DEST_ID = [");                /* each destination's own value (qd_quad_dest_id), -1 none */
    for (k = 0; k < qd_quad_ndest(); k++)
        printf("%s%d", k ? ", " : "", qd_quad_dest_id(k));
    printf("];\n");
    {   /* the LFO destinations, the editor's order (qd_quad_dest_step from NONE) */
        int d = 0, n = qd_quad_ndest();
        printf("export const DEST_ORDER = [0");
        for (k = 1; k < n; k++) {
            const int e = qd_quad_dest_step(d, 1);
            if (e == d)
                break;
            printf(", %d", e);
            d = e;
        }
        printf("];\n");
    }
    return 0;
}
